import pandas as pd, numpy as np
a=pd.read_csv('assessments.csv',usecols=['tmk','tax_year','property_class','assessed_land_value','assessed_building_value','land_exemption','building_exemption'],dtype={'tmk':str})
a=a[a.tmk.str[0]=='1'].copy()
p=a.tmk.str.split('-',expand=True)
a['tmk8']=p[1]+p[2]+p[3].str.zfill(3)+p[4].str.zfill(3)
a['EX']=a.land_exemption.fillna(0)+a.building_exemption.fillna(0)
a=a.drop_duplicates(['tmk','tax_year'])
g=a.groupby(['tmk8','tax_year']).agg(L=('assessed_land_value','sum'),B=('assessed_building_value','sum'),EX=('EX','sum'),nrec=('tmk','size'),cls=('property_class','first')).reset_index()
g.to_pickle('hnl_panel.pkl')
d=pd.read_pickle('d.pkl')
c=g[g.tax_year==2022].set_index('tmk8').join(d[['L','B','EX','nrec']],rsuffix='_roll',how='inner')
print('2022 overlap',len(c),'of roll',len(d))
for v in ['L','B','EX','nrec']: print(v,'exact match share',round((c[v]==c[v+'_roll']).mean(),4),'median ratio',round((c[v]/c[v+'_roll'].replace(0,np.nan)).median(),3))
print(g.groupby('tax_year').size().to_dict())
